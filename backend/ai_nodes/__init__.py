"""
AI Nodes — Auto-discovered nodes generated by System 1.
This directory is writable at runtime via bind-mount shared with systems container.
"""
import importlib.util, logging, pathlib
logger = logging.getLogger(__name__)
_ai_nodes_dir = pathlib.Path(__file__).parent

def load_ai_nodes():
    loaded = 0
    for path in sorted(_ai_nodes_dir.glob("*.py")):
        if path.name.startswith("_"): continue
        module_name = f"ai_nodes.{path.stem}"
        try:
            spec = importlib.util.spec_from_file_location(module_name, path)
            mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(mod)
            loaded += 1
        except Exception as e:
            logger.error(f"Failed to load ai_node {path.name}: {e}")
    logger.info(f"ai_nodes scan complete: {loaded} modules loaded")

load_ai_nodes()
